from __future__ import annotations

import importlib.util
import json
import sys
import textwrap
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
MODULE_PATH = ROOT / "tools" / "lint_rules.py"


def load_module():
    spec = importlib.util.spec_from_file_location("lint_rules", MODULE_PATH)
    module = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    sys.modules[spec.name] = module  # required for dataclasses and similar
    spec.loader.exec_module(module)
    return module


lr = load_module()


def rules(violations) -> list[str]:
    return [v.rule for v in violations]


def py(src: str) -> list:
    return lr.lint_python_source(textwrap.dedent(src), "tools/sample.py")


# ---------------------------------------------------------------- Violation type


def test_violation_fields():
    v = py("def 函式():\n    pass\n")[0]
    assert v.rule == "non_ascii_identifier"
    assert v.path == "tools/sample.py"
    assert v.line == 1
    assert isinstance(v.message, str) and v.message


# ---------------------------------------------------------------- python: identifiers


@pytest.mark.parametrize("src", [
    "def 函式():\n    pass\n",
    "class 類別:\n    pass\n",
    "名稱 = 1\n",
    "def f(參數):\n    return 參數\n",
    "import os as 系統\n",
    "x = obj.屬性\n",
    "f(值=1)\n",
])
def test_non_ascii_identifier(src):
    assert "non_ascii_identifier" in rules(py(src))


