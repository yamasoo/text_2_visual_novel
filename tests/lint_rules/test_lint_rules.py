# ---------------------------------------------------------------- repo walk


def write(root: Path, rel: str, content: str) -> None:
    p = root / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(content, encoding="utf-8")


def test_lint_repo_scope(tmp_path):
    write(tmp_path, "tools/good.py", "x = 1\n")
    write(tmp_path, "tools/bad.py", 'd = {"章號": 1}\n')
    write(tmp_path, "tools/壞檔名.py", "x = 1\n")
    write(tmp_path, "schema/bad.json", '{"角色": 1}\n')
    write(tmp_path, "config/source_field_map.json", '{"chapter_outline": {"章號": "chapter_no"}}\n')
    write(tmp_path, "config.example.yaml", "書庫: x\n")
    # excluded locations
    write(tmp_path, "docs/中文文件.md", "中文\n")
    write(tmp_path, "docs/notes.json", '{"中文": 1}\n')
    write(tmp_path, "vendor/novel_studio/project.py", 'd = {"正文": 1}\n')
    write(tmp_path, ".venv/lib/x.py", "名稱 = 1\n")
    write(tmp_path, "tests/normalize_book/fixtures/正文/第001章.md", "# 第1章\n")
    write(tmp_path, "works/sample_book/chapters/ch001.json", '{"title": "補囊"}\n')

    v = lr.lint_repo(tmp_path)
    got = sorted((x.path, x.rule) for x in v)
    assert got == [
        ("config.example.yaml", "non_ascii_key"),
        ("schema/bad.json", "non_ascii_key"),
        ("tools/bad.py", "non_ascii_key"),
        ("tools/壞檔名.py", "non_ascii_filename"),
    ]
    assert all("\\" not in x.path for x in v)


def test_lint_repo_sorted(tmp_path):
    write(tmp_path, "tools/b.py", 'd = {"乙": 1}\ne = {"丙": 1}\n')
    write(tmp_path, "tools/a.py", 'd = {"甲": 1}\n')
    v = lr.lint_repo(tmp_path)
    assert [(x.path, x.line) for x in v] == [("tools/a.py", 1), ("tools/b.py", 1), ("tools/b.py", 2)]


def test_lint_repo_extra_allow(tmp_path):
    write(tmp_path, "config/extra_map.json", '{"章號": "chapter_no"}\n')
    assert rules(lr.lint_repo(tmp_path)) == ["non_ascii_key"]
    assert lr.lint_repo(tmp_path, allow=["config/extra_map.json"]) == []


# ---------------------------------------------------------------- CLI


def test_main_clean(tmp_path, capsys):
    write(tmp_path, "tools/good.py", "x = 1\n")
    assert lr.main([str(tmp_path)]) == 0


def test_main_violations(tmp_path, capsys):
    write(tmp_path, "tools/bad.py", 'd = {"章號": 1}\n')
    assert lr.main([str(tmp_path)]) == 1
    out = capsys.readouterr().out
    assert "tools/bad.py:1" in out
    assert "non_ascii_key" in out


def test_main_json(tmp_path, capsys):
    write(tmp_path, "tools/bad.py", 'd = {"章號": 1}\n')
    assert lr.main([str(tmp_path), "--json"]) == 1
    data = json.loads(capsys.readouterr().out)
    assert data == [{"rule": "non_ascii_key", "path": "tools/bad.py", "line": 1, "message": data[0]["message"]}]


def test_main_allow_flag(tmp_path):
    write(tmp_path, "config/extra_map.json", '{"章號": "chapter_no"}\n')
    assert lr.main([str(tmp_path), "--allow", "config/extra_map.json"]) == 0


