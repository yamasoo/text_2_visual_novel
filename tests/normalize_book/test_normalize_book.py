def test_book_dir_is_not_modified(tmp_path):
    book = make_book(tmp_path, [("第001章_開場.md", CH1)])
    before = sorted((p.relative_to(book), p.read_bytes()) for p in book.rglob("*") if p.is_file())
    run(book, tmp_path / "out", write_txt=True)
    after = sorted((p.relative_to(book), p.read_bytes()) for p in book.rglob("*") if p.is_file())
    assert before == after


def test_output_matches_schema_if_jsonschema_available(tmp_path):
    jsonschema = pytest.importorskip("jsonschema")
    book = make_book(tmp_path, [("第001章_開場.md", CH1), ("第002章_第二天.md", CH2)])
