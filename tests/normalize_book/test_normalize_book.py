def test_cli_success(tmp_path, capsys):
    book = make_book(tmp_path, [("第001章_開場.md", CH1)])
    out = tmp_path / "out"
    code = nb.main([
        "--book-dir", str(book), "--book-id", "testbook", "--out", str(out),
        "--chapters", "1-1", "--txt", "--field-map", str(FIELD_MAP_PATH),
    ])
    assert code == 0
    assert (out / "chapters" / "ch001.json").exists()
    assert (out / "chapters" / "book.txt").exists()


