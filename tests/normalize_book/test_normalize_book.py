"""Acceptance tests for tools/normalize_book.py (task t_s1_normalize_book).

All fixture books are synthetic and built in tmp_path. Do not edit this file.
"""
from __future__ import annotations

import hashlib
import importlib.util
import json
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
MODULE_PATH = ROOT / "tools" / "normalize_book.py"
FIELD_MAP_PATH = ROOT / "config" / "source_field_map.json"


def load_module():
    spec = importlib.util.spec_from_file_location("normalize_book", MODULE_PATH)
    module = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    sys.modules[spec.name] = module  # required for dataclasses and similar
    spec.loader.exec_module(module)
    return module


nb = load_module()

FIELD_MAP = json.loads(FIELD_MAP_PATH.read_text(encoding="utf-8"))
TEXT_DIR = FIELD_MAP["source_paths"]["chapter_text_dir"]

CH1 = """# 第1章 開場

　　天剛亮，碼頭上已經有人在搬貨。

「早。」她說。

***

午後下起雨來。
"""

CH2 = """﻿# 第2章 第二天\r
\r
第一段。\r
## 小標題\r
第二段。\r
"""


def make_book(tmp_path: Path, files: list[tuple[str, str | bytes]]) -> Path:
    book = tmp_path / "library" / "test_book"
    text_dir = book / TEXT_DIR
    text_dir.mkdir(parents=True)
    for name, content in files:
        p = text_dir / name
        if isinstance(content, bytes):
            p.write_bytes(content)
        else:
            p.write_bytes(content.encode("utf-8"))
    return book


def run(book: Path, out: Path, **kwargs):
    return nb.normalize_book(book, "testbook", out, field_map_path=FIELD_MAP_PATH, **kwargs)


def read_json(p: Path):
    return json.loads(p.read_text(encoding="utf-8"))


# ---------------------------------------------------------------- normal cases


def test_basic_chapter(tmp_path):
    book = make_book(tmp_path, [("第001章_開場.md", CH1), (".gitkeep", "")])
    out = tmp_path / "works" / "testbook"
    run(book, out)

    ch = read_json(out / "chapters" / "ch001.json")
    assert ch["schema_version"] == "0.1"
    assert ch["book_id"] == "testbook"
    assert ch["chapter_id"] == "ch001"
    assert ch["chapter_no"] == 1
    assert ch["title"] == "開場"
    assert ch["source_file"] == f"{TEXT_DIR}/第001章_開場.md"
    assert ch["paragraphs"] == [
        {"para_no": 1, "text": "天剛亮，碼頭上已經有人在搬貨。"},
        {"para_no": 2, "text": "「早。」她說。"},
        {"para_no": 3, "text": "午後下起雨來。"},
    ]
    assert ch["scene_breaks"] == [3]


def test_sha256_and_char_count(tmp_path):
    book = make_book(tmp_path, [("第001章_開場.md", CH1)])
    out = tmp_path / "out"
    run(book, out)
    ch = read_json(out / "chapters" / "ch001.json")
    raw = (book / TEXT_DIR / "第001章_開場.md").read_bytes()
    assert ch["sha256"] == hashlib.sha256(raw).hexdigest()
    expected = sum(len("".join(p["text"].split())) for p in ch["paragraphs"])
    assert ch["char_count"] == expected == 29


